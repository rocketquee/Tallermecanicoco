-- Requisitos: PAG-01 a PAG-07, FAC-01 a FAC-05, AUT-01 a AUT-08
--
-- Requiere haber ejecutado 01_catalogos.sql y 04_ordenes.sql
-- (fn_set_updated_at y ordenes_servicio).
-- El script es idempotente: se puede volver a ejecutar sin perder datos.
