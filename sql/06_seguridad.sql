BEGIN;

-- ---------------------------------------------------------------------
-- Tipos ENUM
-- ---------------------------------------------------------------------
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM pg_type
    WHERE typname = 'rol_usuario'
      AND typnamespace = 'public'::regnamespace
  ) THEN
    CREATE TYPE rol_usuario AS ENUM (
      'Administrador',
      'Recepcion',
      'Mecanico'
    );
  END IF;
END
$$;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM pg_type
    WHERE typname = 'accion_bitacora'
      AND typnamespace = 'public'::regnamespace
  ) THEN
    CREATE TYPE accion_bitacora AS ENUM (
      'Creacion',
      'Actualizacion',
      'Cancelacion',
      'Autorizacion',
      'Consulta_Confidencial'
    );
  END IF;
END
$$;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM pg_type
    WHERE typname = 'etapa_orden_historial'
      AND typnamespace = 'public'::regnamespace
  ) THEN
    CREATE TYPE etapa_orden_historial AS ENUM (
      'Recibido',
      'Diagnostico',
      'Reparacion',
      'Listo',
      'Entregado',
      'Cancelado'
    );
  END IF;
END
$$;

-- ---------------------------------------------------------------------
-- usuarios
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS usuarios (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(150) NOT NULL,
  correo VARCHAR(150) NOT NULL,
  password_hash VARCHAR(255) NOT NULL,
  rol rol_usuario NOT NULL,
  mecanico_id INTEGER NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  activo BOOLEAN NOT NULL DEFAULT TRUE,
  CONSTRAINT fk_usuarios_mecanico
    FOREIGN KEY (mecanico_id) REFERENCES mecanicos (id)
    ON DELETE RESTRICT
    ON UPDATE CASCADE
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_usuarios_correo ON usuarios (correo);
CREATE INDEX IF NOT EXISTS idx_usuarios_rol ON usuarios (rol);
CREATE INDEX IF NOT EXISTS idx_usuarios_mecanico ON usuarios (mecanico_id);

COMMENT ON TABLE usuarios IS 'Usuarios del sistema con roles Administrador, Recepcion y Mecanico (SEG-01 a SEG-04)';
COMMENT ON COLUMN usuarios.id IS 'Identificador interno del usuario del sistema (SEG-01)';
COMMENT ON COLUMN usuarios.nombre IS 'Nombre completo del usuario: administrador, recepción o mecánico (SEG-01)';
COMMENT ON COLUMN usuarios.correo IS 'Correo de acceso; identificador único de autenticación (SEG-01)';
COMMENT ON COLUMN usuarios.password_hash IS 'Contraseña cifrada con hash; nunca en texto plano (SEG-01, SEG-15)';
COMMENT ON COLUMN usuarios.rol IS 'Rol que define permisos: acceso total, sin finanzas o solo placas y trabajo (SEG-01, SEG-02, SEG-03, SEG-04, SEG-18)';
COMMENT ON COLUMN usuarios.mecanico_id IS 'Vínculo opcional al catálogo de mecánicos cuando el usuario lo es; FK a mecanicos.id (SEG-01, ORD-09, REP-03)';
COMMENT ON COLUMN usuarios.created_at IS 'Fecha y hora de alta del usuario (auditoría SEG-06)';
COMMENT ON COLUMN usuarios.updated_at IS 'Fecha y hora de la última modificación (auditoría SEG-06)';
COMMENT ON COLUMN usuarios.activo IS 'Borrado lógico: TRUE vigente, FALSE dado de baja; el usuario no se elimina (SEG-07)';

DROP TRIGGER IF EXISTS trg_usuarios_updated_at ON usuarios;
CREATE TRIGGER trg_usuarios_updated_at
BEFORE UPDATE ON usuarios
FOR EACH ROW EXECUTE FUNCTION fn_set_updated_at();

-- ---------------------------------------------------------------------
-- bitacora (INMUTABLE: solo created_at, sin updated_at ni activo)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS bitacora (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id INTEGER NOT NULL,
  tabla_afectada VARCHAR(100) NOT NULL,
  registro_id INTEGER NOT NULL,
  accion accion_bitacora NOT NULL,
  detalle TEXT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_bitacora_usuario
    FOREIGN KEY (usuario_id) REFERENCES usuarios (id)
    ON DELETE RESTRICT
    ON UPDATE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_bitacora_usuario ON bitacora (usuario_id);
CREATE INDEX IF NOT EXISTS idx_bitacora_registro ON bitacora (tabla_afectada, registro_id);
CREATE INDEX IF NOT EXISTS idx_bitacora_fecha ON bitacora (created_at);
CREATE INDEX IF NOT EXISTS idx_bitacora_accion ON bitacora (accion);

COMMENT ON TABLE bitacora IS 'Bitácora de auditoría inmutable de altas, cambios, cancelaciones y autorizaciones (SEG-06)';
COMMENT ON COLUMN bitacora.id IS 'Identificador interno del asiento de bitácora (SEG-06)';
COMMENT ON COLUMN bitacora.usuario_id IS 'Usuario que ejecutó la acción; FK a usuarios.id (SEG-06, ORD-08)';
COMMENT ON COLUMN bitacora.tabla_afectada IS 'Tabla sobre la que se actuó, por ejemplo ordenes_servicio o facturas (SEG-06)';
COMMENT ON COLUMN bitacora.registro_id IS 'Identificador del registro afectado dentro de esa tabla (SEG-06)';
COMMENT ON COLUMN bitacora.accion IS 'Tipo de evento auditado: alta, cambio, cancelación, autorización o consulta a expediente confidencial (SEG-06, SEG-20)';
COMMENT ON COLUMN bitacora.detalle IS 'Valores o contexto del cambio, en formato legible, para reconstruir qué pasó (SEG-06)';
COMMENT ON COLUMN bitacora.created_at IS 'Fecha y hora exacta del evento; la bitácora es inmutable y no se edita (SEG-06, ORD-08)';

-- La bitacora debe ser inmutable (SEG-06). TRUNCATE sigue permitido para
-- limpiezas de desarrollo: en PostgreSQL no dispara los triggers de DELETE.
CREATE OR REPLACE FUNCTION fn_bitacora_inmutable()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  IF TG_OP = 'DELETE' THEN
    RAISE EXCEPTION
      'bitacora: es inmutable, no se permite borrar asientos'
      USING ERRCODE = 'P0001';
  END IF;
  RAISE EXCEPTION
    'bitacora: es inmutable, no se permite modificar asientos'
    USING ERRCODE = 'P0001';
END;
$$;

DROP TRIGGER IF EXISTS trg_bitacora_bu ON bitacora;
CREATE TRIGGER trg_bitacora_bu
BEFORE UPDATE ON bitacora
FOR EACH ROW EXECUTE FUNCTION fn_bitacora_inmutable();

DROP TRIGGER IF EXISTS trg_bitacora_bd ON bitacora;
CREATE TRIGGER trg_bitacora_bd
BEFORE DELETE ON bitacora
FOR EACH ROW EXECUTE FUNCTION fn_bitacora_inmutable();

