BEGIN;

-- ---------------------------------------------------------------------
-- Tipos ENUM
-- ---------------------------------------------------------------------
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM pg_type
    WHERE typname = 'estado_compra'
      AND typnamespace = 'public'::regnamespace
  ) THEN
    CREATE TYPE estado_compra AS ENUM (
      'Borrador',
      'Aprobada',
      'Enviada',
      'Recibida',
      'Cancelada'
    );
  END IF;
END
$$;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM pg_type
    WHERE typname = 'moneda_compra'
      AND typnamespace = 'public'::regnamespace
  ) THEN
    CREATE TYPE moneda_compra AS ENUM ('EUR', 'GBP', 'MXN', 'USD');
  END IF;
END
$$;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM pg_type
    WHERE typname = 'tipo_movimiento'
      AND typnamespace = 'public'::regnamespace
  ) THEN
    CREATE TYPE tipo_movimiento AS ENUM ('Entrada', 'Salida', 'Ajuste');
  END IF;
END
$$;

-- ---------------------------------------------------------------------
-- refacciones
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS refacciones (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(150) NOT NULL,
  marca VARCHAR(50) NULL,
  es_especial BOOLEAN NOT NULL DEFAULT FALSE,
  stock_actual INTEGER NOT NULL DEFAULT 0,
  stock_minimo INTEGER NOT NULL DEFAULT 2,
  precio_costo NUMERIC(12, 2) NOT NULL,
  precio_venta NUMERIC(12, 2) NOT NULL,
  proveedor_id INTEGER NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  activo BOOLEAN NOT NULL DEFAULT TRUE,
  CONSTRAINT fk_refacciones_proveedor
    FOREIGN KEY (proveedor_id) REFERENCES proveedores (id)
    ON DELETE RESTRICT
    ON UPDATE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_refacciones_proveedor ON refacciones (proveedor_id);
CREATE INDEX IF NOT EXISTS idx_refacciones_nombre ON refacciones (nombre);
CREATE INDEX IF NOT EXISTS idx_refacciones_stock ON refacciones (stock_actual, stock_minimo);
CREATE INDEX IF NOT EXISTS idx_refacciones_especial ON refacciones (es_especial);

COMMENT ON TABLE refacciones IS 'Catálogo de refacciones y consumibles con existencias (INV-01 a INV-05)';
COMMENT ON COLUMN refacciones.id IS 'Identificador interno de la refacción o consumible (INV-01)';
COMMENT ON COLUMN refacciones.nombre IS 'Nombre o descripción de la pieza de tornillería o consumible (INV-01)';
COMMENT ON COLUMN refacciones.marca IS 'Marca de la pieza, usada para distinguir piezas especiales (INV-04)';
COMMENT ON COLUMN refacciones.es_especial IS 'Pieza especial por marca: se compra ligada a una orden, sin existencias en inventario (INV-04)';
COMMENT ON COLUMN refacciones.stock_actual IS 'Existencias actuales en inventario; índice de alerta (INV-01, INV-03)';
COMMENT ON COLUMN refacciones.stock_minimo IS 'Umbral mínimo: alertar con 2 o menos unidades (INV-03)';
COMMENT ON COLUMN refacciones.precio_costo IS 'Costo de adquisición de la refacción (INV-01, SEG-02)';
COMMENT ON COLUMN refacciones.precio_venta IS 'Precio de venta al cliente (INV-01, SEG-02)';
COMMENT ON COLUMN refacciones.proveedor_id IS 'Proveedor habitual de la pieza; FK a proveedores.id (PRV-01)';
COMMENT ON COLUMN refacciones.created_at IS 'Fecha y hora de alta del registro (auditoría SEG-06)';
COMMENT ON COLUMN refacciones.updated_at IS 'Fecha y hora de la última modificación; también refleja ajustes de inventario (INV-05, SEG-06)';
COMMENT ON COLUMN refacciones.activo IS 'Borrado lógico: TRUE vigente, FALSE eliminado (SEG-07)';

DROP TRIGGER IF EXISTS trg_refacciones_updated_at ON refacciones;
CREATE TRIGGER trg_refacciones_updated_at
BEFORE UPDATE ON refacciones
FOR EACH ROW EXECUTE FUNCTION fn_set_updated_at();

-- ---------------------------------------------------------------------
-- compras
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS compras (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  proveedor_id INTEGER NOT NULL,
  orden_id INTEGER NULL,
  fecha_pedido TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  fecha_estimada_llegada DATE NULL,
  estado estado_compra NOT NULL DEFAULT 'Borrador',
  moneda_original moneda_compra NOT NULL,
  tipo_cambio NUMERIC(10, 4) NULL,
  total_moneda_original NUMERIC(12, 2) NULL,
  total_mxn NUMERIC(12, 2) NULL,
  solicitado_por VARCHAR(150) NULL,
  aprobado_por VARCHAR(150) NULL,
  fecha_aprobacion TIMESTAMP NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  activo BOOLEAN NOT NULL DEFAULT TRUE,
  CONSTRAINT fk_compras_proveedor
    FOREIGN KEY (proveedor_id) REFERENCES proveedores (id)
    ON DELETE RESTRICT
    ON UPDATE CASCADE
  -- fk_compras_orden se agrega en 04_ordenes.sql, cuando exista ordenes_servicio.
);

CREATE INDEX IF NOT EXISTS idx_compras_proveedor ON compras (proveedor_id);
CREATE INDEX IF NOT EXISTS idx_compras_orden ON compras (orden_id);
CREATE INDEX IF NOT EXISTS idx_compras_estado ON compras (estado);
CREATE INDEX IF NOT EXISTS idx_compras_fecha_estimada ON compras (fecha_estimada_llegada);

COMMENT ON TABLE compras IS 'Órdenes de compra a proveedores internacionales (PRV-03 a PRV-09)';
COMMENT ON COLUMN compras.id IS 'Identificador interno de la orden de compra (PRV-03)';
COMMENT ON COLUMN compras.proveedor_id IS 'Proveedor al que se le compra; FK a proveedores.id (PRV-01, PRV-03)';
COMMENT ON COLUMN compras.orden_id IS 'Orden de servicio que motivó la compra; FK pendiente a ordenes_servicio.id (PRV-05)';
COMMENT ON COLUMN compras.fecha_pedido IS 'Fecha y hora en que se registra el pedido (PRV-03)';
COMMENT ON COLUMN compras.fecha_estimada_llegada IS 'Fecha estimada de llegada para la lista de pedidos pendientes (PRV-03, PRV-04)';
COMMENT ON COLUMN compras.estado IS 'Estado del pedido; no se envía sin aprobación del admin (PRV-03, PRV-07)';
COMMENT ON COLUMN compras.moneda_original IS 'Moneda original de la compra (PRV-09)';
COMMENT ON COLUMN compras.tipo_cambio IS 'Tipo de cambio del día de la compra para calcular el equivalente en MXN (PRV-09)';
COMMENT ON COLUMN compras.total_moneda_original IS 'Total de la compra en su moneda original (PRV-09)';
COMMENT ON COLUMN compras.total_mxn IS 'Equivalente en pesos mexicanos al tipo de cambio aplicado (PRV-09, PAG-07)';
COMMENT ON COLUMN compras.solicitado_por IS 'Quién solicitó el pedido; evita piezas sin responsable (PRV-05)';
COMMENT ON COLUMN compras.aprobado_por IS 'Usuario administrador que aprobó la orden de compra (PRV-07, AUT-03)';
COMMENT ON COLUMN compras.fecha_aprobacion IS 'Fecha y hora de la aprobación del administrador (PRV-07, SEG-06)';
COMMENT ON COLUMN compras.created_at IS 'Fecha y hora de alta del registro (auditoría SEG-06)';
COMMENT ON COLUMN compras.updated_at IS 'Fecha y hora de la última modificación (auditoría SEG-06)';
COMMENT ON COLUMN compras.activo IS 'Borrado lógico: TRUE vigente, FALSE eliminado (SEG-07)';

DROP TRIGGER IF EXISTS trg_compras_updated_at ON compras;
CREATE TRIGGER trg_compras_updated_at
BEFORE UPDATE ON compras
FOR EACH ROW EXECUTE FUNCTION fn_set_updated_at();

-- ---------------------------------------------------------------------
-- detalle_compra
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS detalle_compra (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  compra_id INTEGER NOT NULL,
  refaccion_id INTEGER NOT NULL,
  cantidad INTEGER NOT NULL,
  precio_unitario_moneda NUMERIC(12, 2) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  activo BOOLEAN NOT NULL DEFAULT TRUE,
  CONSTRAINT fk_detalle_compra_compra
    FOREIGN KEY (compra_id) REFERENCES compras (id)
    ON DELETE RESTRICT
    ON UPDATE CASCADE,
  CONSTRAINT fk_detalle_compra_refaccion
    FOREIGN KEY (refaccion_id) REFERENCES refacciones (id)
    ON DELETE RESTRICT
    ON UPDATE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_detalle_compra_compra ON detalle_compra (compra_id);
CREATE INDEX IF NOT EXISTS idx_detalle_compra_refaccion ON detalle_compra (refaccion_id);

COMMENT ON TABLE detalle_compra IS 'Detalle de piezas por orden de compra (tabla puente compras-refacciones)';
COMMENT ON COLUMN detalle_compra.id IS 'Identificador interno de la línea de compra';
COMMENT ON COLUMN detalle_compra.compra_id IS 'Orden de compra a la que pertenece la línea; FK a compras.id (PRV-03)';
COMMENT ON COLUMN detalle_compra.refaccion_id IS 'Refacción o pieza solicitada; FK a refacciones.id (INV-01, INV-04)';
COMMENT ON COLUMN detalle_compra.cantidad IS 'Cantidad de piezas pedidas en esta línea (PRV-03)';
COMMENT ON COLUMN detalle_compra.precio_unitario_moneda IS 'Precio unitario en la moneda original de la compra (PRV-09)';
COMMENT ON COLUMN detalle_compra.created_at IS 'Fecha y hora de alta del registro (auditoría SEG-06)';
COMMENT ON COLUMN detalle_compra.updated_at IS 'Fecha y hora de la última modificación (auditoría SEG-06)';
COMMENT ON COLUMN detalle_compra.activo IS 'Borrado lógico: TRUE vigente, FALSE eliminado (SEG-07)';

DROP TRIGGER IF EXISTS trg_detalle_compra_updated_at ON detalle_compra;
CREATE TRIGGER trg_detalle_compra_updated_at
BEFORE UPDATE ON detalle_compra
FOR EACH ROW EXECUTE FUNCTION fn_set_updated_at();

-- ---------------------------------------------------------------------
-- movimientos_inventario
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS movimientos_inventario (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  refaccion_id INTEGER NOT NULL,
  tipo tipo_movimiento NOT NULL,
  cantidad INTEGER NOT NULL,
  motivo VARCHAR(255) NULL,
  usuario VARCHAR(150) NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  activo BOOLEAN NOT NULL DEFAULT TRUE,
  CONSTRAINT fk_movimientos_refaccion
    FOREIGN KEY (refaccion_id) REFERENCES refacciones (id)
    ON DELETE RESTRICT
    ON UPDATE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_movimientos_refaccion ON movimientos_inventario (refaccion_id);
CREATE INDEX IF NOT EXISTS idx_movimientos_tipo ON movimientos_inventario (tipo);
CREATE INDEX IF NOT EXISTS idx_movimientos_fecha ON movimientos_inventario (created_at);

COMMENT ON TABLE movimientos_inventario IS 'Trazabilidad de entradas, salidas y ajustes de inventario (INV-02, INV-05)';
COMMENT ON COLUMN movimientos_inventario.id IS 'Identificador interno del movimiento de inventario (INV-02, INV-05)';
COMMENT ON COLUMN movimientos_inventario.refaccion_id IS 'Refacción afectada; FK a refacciones.id (INV-02)';
COMMENT ON COLUMN movimientos_inventario.tipo IS 'Tipo de movimiento: entrada por compra, salida por uso en orden o ajuste manual (INV-02, INV-05)';
COMMENT ON COLUMN movimientos_inventario.cantidad IS 'Unidades del movimiento (siempre positiva; el tipo define el sentido) (INV-02, INV-05)';
COMMENT ON COLUMN movimientos_inventario.motivo IS 'Motivo obligatorio en ajustes manuales (INV-05)';
COMMENT ON COLUMN movimientos_inventario.usuario IS 'Usuario que registró el movimiento, para la bitácora (INV-05, SEG-06)';
COMMENT ON COLUMN movimientos_inventario.created_at IS 'Fecha y hora del movimiento (auditoría SEG-06)';
COMMENT ON COLUMN movimientos_inventario.updated_at IS 'Fecha y hora de la última modificación (auditoría SEG-06)';
COMMENT ON COLUMN movimientos_inventario.activo IS 'Borrado lógico: TRUE vigente, FALSE eliminado (SEG-07)';

DROP TRIGGER IF EXISTS trg_movimientos_inventario_updated_at ON movimientos_inventario;
CREATE TRIGGER trg_movimientos_inventario_updated_at
BEFORE UPDATE ON movimientos_inventario
FOR EACH ROW EXECUTE FUNCTION fn_set_updated_at();

COMMIT;
