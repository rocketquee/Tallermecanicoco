BEGIN;

-- ---------------------------------------------------------------------
-- Tipos ENUM
-- PostgreSQL no tiene ENUM en línea: cada tipo se crea una sola vez.
-- ---------------------------------------------------------------------
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM pg_type
    WHERE typname = 'categoria_cliente'
      AND typnamespace = 'public'::regnamespace
  ) THEN
    CREATE TYPE categoria_cliente AS ENUM ('Regular', 'VIP');
  END IF;
END
$$;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM pg_type
    WHERE typname = 'moneda_proveedor'
      AND typnamespace = 'public'::regnamespace
  ) THEN
    CREATE TYPE moneda_proveedor AS ENUM ('EUR', 'GBP', 'MXN', 'USD');
  END IF;
END
$$;

-- ---------------------------------------------------------------------
-- Función compartida para emular ON UPDATE CURRENT_TIMESTAMP de MySQL.
-- Los bloques siguientes la reutilizan en sus propias tablas.
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_set_updated_at()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  NEW.updated_at = CURRENT_TIMESTAMP;
  RETURN NEW;
END;
$$;

-- ---------------------------------------------------------------------
-- clientes
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS clientes (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(150) NOT NULL,
  telefono1 VARCHAR(20) NULL,
  telefono2 VARCHAR(20) NULL,
  correo VARCHAR(150) NULL,
  direccion VARCHAR(255) NULL,
  nombre_asistente VARCHAR(150) NULL,
  categoria categoria_cliente NOT NULL DEFAULT 'Regular',
  descuento_mano_obra NUMERIC(5, 2) NOT NULL DEFAULT 0.00,
  permite_pagos_parciales BOOLEAN NOT NULL DEFAULT FALSE,
  confidencial BOOLEAN NOT NULL DEFAULT FALSE,
  notas TEXT NULL,
  rfc VARCHAR(20) NULL,
  razon_social VARCHAR(200) NULL,
  regimen_fiscal VARCHAR(100) NULL,
  codigo_postal VARCHAR(10) NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  activo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE INDEX IF NOT EXISTS idx_clientes_nombre ON clientes (nombre);
CREATE INDEX IF NOT EXISTS idx_clientes_categoria ON clientes (categoria);
CREATE INDEX IF NOT EXISTS idx_clientes_confidencial ON clientes (confidencial);

COMMENT ON TABLE clientes IS 'Clientes del taller, incluidos VIP y confidenciales (CLI-01 a CLI-06)';
COMMENT ON COLUMN clientes.id IS 'Identificador interno del cliente (CLI-01)';
COMMENT ON COLUMN clientes.nombre IS 'Nombre del dueño del vehículo; búsqueda indexada <3s (CLI-01, CLI-05)';
COMMENT ON COLUMN clientes.telefono1 IS 'Teléfono principal de contacto (CLI-01)';
COMMENT ON COLUMN clientes.telefono2 IS 'Teléfono secundario de contacto (CLI-01)';
COMMENT ON COLUMN clientes.correo IS 'Correo electrónico de contacto (CLI-01)';
COMMENT ON COLUMN clientes.direccion IS 'Dirección del cliente (CLI-01)';
COMMENT ON COLUMN clientes.nombre_asistente IS 'Nombre del asistente o chofer del cliente (CLI-01)';
COMMENT ON COLUMN clientes.categoria IS 'Categoría del cliente; VIP recibe prioridad en la fila de órdenes (CLI-02, CLI-03, ORD-13)';
COMMENT ON COLUMN clientes.descuento_mano_obra IS 'Porcentaje de descuento aplicable solo a mano de obra; VIP = 10.00 (CLI-03, PAG-02)';
COMMENT ON COLUMN clientes.permite_pagos_parciales IS 'Autoriza pagos en partes solo a clientes de confianza (PAG-04)';
COMMENT ON COLUMN clientes.confidencial IS 'Cliente confidencial: el mecánico solo ve placas y trabajo asignado (SEG-17, SEG-18, SEG-19)';
COMMENT ON COLUMN clientes.notas IS 'Notas internas de atención al cliente';
COMMENT ON COLUMN clientes.rfc IS 'RFC del cliente para CFDI 4.0 (FAC-05)';
COMMENT ON COLUMN clientes.razon_social IS 'Razón social o nombre fiscal para CFDI 4.0 (FAC-05)';
COMMENT ON COLUMN clientes.regimen_fiscal IS 'Régimen fiscal del cliente requerido por CFDI 4.0 (FAC-05)';
COMMENT ON COLUMN clientes.codigo_postal IS 'Código postal del domicilio fiscal requerido por CFDI 4.0 (FAC-05)';
COMMENT ON COLUMN clientes.created_at IS 'Fecha y hora de alta del registro (auditoría SEG-06)';
COMMENT ON COLUMN clientes.updated_at IS 'Fecha y hora de la última modificación (auditoría SEG-06)';
COMMENT ON COLUMN clientes.activo IS 'Borrado lógico: TRUE vigente, FALSE eliminado (SEG-07)';

DROP TRIGGER IF EXISTS trg_clientes_updated_at ON clientes;
CREATE TRIGGER trg_clientes_updated_at
BEFORE UPDATE ON clientes
FOR EACH ROW EXECUTE FUNCTION fn_set_updated_at();

