COMMENT ON COLUMN ordenes_servicio.mecanico_id IS 'Mecánico principal o responsable de la orden; FK a mecanicos.id. Los demás participantes viven en orden_mecanicos (ORD-09)';
COMMENT ON COLUMN ordenes_servicio.estado IS 'Etapa de la orden: recibido, diagnóstico, reparación, listo, entregado o cancelado (ORD-02, ORD-04, ORD-05, ORD-11)';
COMMENT ON COLUMN ordenes_servicio.falla_reportada IS 'Falla o motivo de ingreso reportado por el cliente (ORD-01)';
COMMENT ON COLUMN ordenes_servicio.diagnostico IS 'Diagnostico y notas del mecanico; separado de la falla reportada por el cliente (ORD-04, ORD-10)';
COMMENT ON COLUMN ordenes_servicio.total_piezas IS 'Suma de refacciones usadas en la orden (PAG-01)';
