-- ---------------------------------------------------------------------
-- detalle_orden
-- Cada línea es O mano de obra O refacción, nunca las dos y nunca ninguna.
-- En PostgreSQL sí se podría usar un CHECK, pero se conservan los triggers
-- para mantener la misma regla y los mismos nombres que documenta el modelo.
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS detalle_orden (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  orden_id INTEGER NOT NULL,
  servicio_id INTEGER NULL,
  refaccion_id INTEGER NULL,
  cantidad INTEGER NOT NULL,
  precio_unitario NUMERIC(12, 2) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  activo BOOLEAN NOT NULL DEFAULT TRUE,
  CONSTRAINT fk_detalle_orden_orden
    FOREIGN KEY (orden_id) REFERENCES ordenes_servicio (id)
    ON DELETE RESTRICT
    ON UPDATE CASCADE,
  CONSTRAINT fk_detalle_orden_servicio
    FOREIGN KEY (servicio_id) REFERENCES servicios (id)
    ON DELETE RESTRICT
    ON UPDATE CASCADE,
  CONSTRAINT fk_detalle_orden_refaccion
    FOREIGN KEY (refaccion_id) REFERENCES refacciones (id)
    ON DELETE RESTRICT
    ON UPDATE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_detalle_orden_orden ON detalle_orden (orden_id);
CREATE INDEX IF NOT EXISTS idx_detalle_orden_servicio ON detalle_orden (servicio_id);
CREATE INDEX IF NOT EXISTS idx_detalle_orden_refaccion ON detalle_orden (refaccion_id);

COMMENT ON TABLE detalle_orden IS 'Detalle de piezas y mano de obra por orden (ORD-10, INV-02)';
COMMENT ON COLUMN detalle_orden.id IS 'Identificador interno de la línea de la orden (ORD-10)';
COMMENT ON COLUMN detalle_orden.orden_id IS 'Orden de servicio a la que pertenece la línea; FK a ordenes_servicio.id (ORD-10)';
COMMENT ON COLUMN detalle_orden.servicio_id IS 'Servicio o mano de obra aplicada; FK a servicios.id; excluyente con refaccion_id (ORD-10)';
COMMENT ON COLUMN detalle_orden.refaccion_id IS 'Refacción o consumible usado; FK a refacciones.id; excluyente con servicio_id (ORD-10, INV-02)';
COMMENT ON COLUMN detalle_orden.cantidad IS 'Cantidad de servicios o piezas de la línea (ORD-10)';
COMMENT ON COLUMN detalle_orden.precio_unitario IS 'Precio unitario al momento de la venta, para conservar historial (ORD-10, PAG-01)';
COMMENT ON COLUMN detalle_orden.created_at IS 'Fecha y hora de alta del registro (auditoría SEG-06)';
COMMENT ON COLUMN detalle_orden.updated_at IS 'Fecha y hora de la última modificación (auditoría SEG-06)';
COMMENT ON COLUMN detalle_orden.activo IS 'Borrado lógico: TRUE vigente, FALSE eliminado (SEG-07)';

DROP TRIGGER IF EXISTS trg_detalle_orden_updated_at ON detalle_orden;
CREATE TRIGGER trg_detalle_orden_updated_at
BEFORE UPDATE ON detalle_orden
FOR EACH ROW EXECUTE FUNCTION fn_set_updated_at();

-- Regla XOR (ADR-005). El ERRCODE P0001 permite que la API lo traduzca a 422.
CREATE OR REPLACE FUNCTION fn_validar_detalle_orden_xor()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  IF (NEW.servicio_id IS NULL AND NEW.refaccion_id IS NULL)
     OR (NEW.servicio_id IS NOT NULL AND NEW.refaccion_id IS NOT NULL) THEN
    RAISE EXCEPTION
      'detalle_orden: debe indicar servicio_id o refaccion_id, pero no ambos'
      USING ERRCODE = 'P0001';
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_detalle_orden_bi ON detalle_orden;
CREATE TRIGGER trg_detalle_orden_bi
BEFORE INSERT ON detalle_orden
FOR EACH ROW EXECUTE FUNCTION fn_validar_detalle_orden_xor();

DROP TRIGGER IF EXISTS trg_detalle_orden_bu ON detalle_orden;
CREATE TRIGGER trg_detalle_orden_bu
BEFORE UPDATE ON detalle_orden
FOR EACH ROW EXECUTE FUNCTION fn_validar_detalle_orden_xor();

