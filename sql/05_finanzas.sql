BEGIN;

-- ---------------------------------------------------------------------
-- Tipos ENUM
-- ---------------------------------------------------------------------
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM pg_type
    WHERE typname = 'tipo_pago'
      AND typnamespace = 'public'::regnamespace
  ) THEN
    CREATE TYPE tipo_pago AS ENUM ('Anticipo', 'Parcialidad', 'Liquidacion');
  END IF;
END
$$;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM pg_type
    WHERE typname = 'metodo_pago'
      AND typnamespace = 'public'::regnamespace
  ) THEN
    CREATE TYPE metodo_pago AS ENUM ('Efectivo', 'Transferencia', 'Tarjeta');
  END IF;
END
$$;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM pg_type
    WHERE typname = 'estado_factura'
      AND typnamespace = 'public'::regnamespace
  ) THEN
    CREATE TYPE estado_factura AS ENUM ('Borrador', 'Timbrada', 'Cancelada');
  END IF;
END
$$;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM pg_type
    WHERE typname = 'tipo_autorizacion'
      AND typnamespace = 'public'::regnamespace
  ) THEN
    CREATE TYPE tipo_autorizacion AS ENUM (
      'Monto_Alto',
      'Saldo_Pendiente',
      'Reautorizacion'
    );
  END IF;
END
$$;

-- ---------------------------------------------------------------------
-- pagos
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS pagos (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  orden_id INTEGER NOT NULL,
  tipo tipo_pago NOT NULL,
  monto NUMERIC(12, 2) NOT NULL,
  metodo_pago metodo_pago NOT NULL DEFAULT 'Transferencia',
  referencia VARCHAR(100) NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  activo BOOLEAN NOT NULL DEFAULT TRUE,
  CONSTRAINT fk_pagos_orden
    FOREIGN KEY (orden_id) REFERENCES ordenes_servicio (id)
    ON DELETE RESTRICT
    ON UPDATE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_pagos_orden ON pagos (orden_id);
CREATE INDEX IF NOT EXISTS idx_pagos_tipo ON pagos (tipo);
CREATE INDEX IF NOT EXISTS idx_pagos_fecha ON pagos (created_at);

COMMENT ON TABLE pagos IS 'Anticipos, parcialidades y liquidaciones por orden (PAG-03 a PAG-05, PAG-07)';
COMMENT ON COLUMN pagos.id IS 'Identificador interno del pago (PAG-03)';
COMMENT ON COLUMN pagos.orden_id IS 'Orden de servicio que se está pagando; FK a ordenes_servicio.id (PAG-03, PAG-05)';
COMMENT ON COLUMN pagos.tipo IS 'Naturaleza del pago: anticipo del 50%, parcialidad o liquidación final (PAG-03, PAG-04)';
COMMENT ON COLUMN pagos.monto IS 'Monto entregado en pesos mexicanos; siempre se cobra en MXN (PAG-03, PAG-07)';
COMMENT ON COLUMN pagos.metodo_pago IS 'Forma de pago utilizada por el cliente (PAG-03)';
COMMENT ON COLUMN pagos.referencia IS 'Referencia o folio de la operación, típicamente número de transferencia (PAG-03)';
COMMENT ON COLUMN pagos.created_at IS 'Fecha y hora en que se registró el pago; base del historial del cliente (PAG-05, CLI-06, SEG-06)';
COMMENT ON COLUMN pagos.updated_at IS 'Fecha y hora de la última modificación (auditoría SEG-06)';
COMMENT ON COLUMN pagos.activo IS 'Borrado lógico: TRUE vigente, FALSE eliminado (SEG-07)';

DROP TRIGGER IF EXISTS trg_pagos_updated_at ON pagos;
CREATE TRIGGER trg_pagos_updated_at
BEFORE UPDATE ON pagos
FOR EACH ROW EXECUTE FUNCTION fn_set_updated_at();

-- ---------------------------------------------------------------------
-- facturas
-- Los dos indices UNIQUE son sobre columnas NULLables. PostgreSQL, igual
-- que MySQL, permite varios NULL en un UNIQUE (NULLS DISTINCT por omision),
-- asi que varias facturas en Borrador pueden no tener folio ni UUID.
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS facturas (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  orden_id INTEGER NOT NULL,
  numero_factura VARCHAR(50) NULL,
  subtotal NUMERIC(12, 2) NOT NULL,
  iva NUMERIC(12, 2) NOT NULL,
  total NUMERIC(12, 2) NOT NULL,
  estado estado_factura NOT NULL DEFAULT 'Borrador',
  uuid_cfdi VARCHAR(100) NULL,
  uso_cfdi VARCHAR(10) NULL,
  forma_pago VARCHAR(10) NULL,
  metodo_pago VARCHAR(10) NULL,
  motivo_cancelacion TEXT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  activo BOOLEAN NOT NULL DEFAULT TRUE,
  CONSTRAINT fk_facturas_orden
    FOREIGN KEY (orden_id) REFERENCES ordenes_servicio (id)
    ON DELETE RESTRICT
    ON UPDATE CASCADE
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_facturas_numero ON facturas (numero_factura);
CREATE UNIQUE INDEX IF NOT EXISTS uq_facturas_uuid ON facturas (uuid_cfdi);
CREATE INDEX IF NOT EXISTS idx_facturas_orden ON facturas (orden_id);
CREATE INDEX IF NOT EXISTS idx_facturas_estado ON facturas (estado);

COMMENT ON TABLE facturas IS 'Facturas CFDI 4.0 listas para timbrar por orden (FAC-01 a FAC-05)';
COMMENT ON COLUMN facturas.id IS 'Identificador interno de la factura (FAC-01)';
COMMENT ON COLUMN facturas.orden_id IS 'Orden que se factura; FK a ordenes_servicio.id (FAC-01, FAC-03)';
COMMENT ON COLUMN facturas.numero_factura IS 'Folio fiscal de la factura; se llena al timbrar con el PAC (FAC-03, FAC-05)';
COMMENT ON COLUMN facturas.subtotal IS 'Subtotal de la factura: piezas más mano de obra (FAC-03, PAG-01)';
COMMENT ON COLUMN facturas.iva IS 'IVA del 16% trasladado en la factura (FAC-03, PAG-01)';
COMMENT ON COLUMN facturas.total IS 'Total facturado al cliente (FAC-03, PAG-01)';
COMMENT ON COLUMN facturas.estado IS 'Estado de la factura; una emitida no se edita y su cancelación requiere motivo (FAC-02, FAC-04)';
COMMENT ON COLUMN facturas.uuid_cfdi IS 'UUID del CFDI 4.0 devuelto por el PAC al timbrar (FAC-05, FAC-06)';
COMMENT ON COLUMN facturas.uso_cfdi IS 'Uso del CFDI declarado por el cliente, catálogo SAT (FAC-05)';
COMMENT ON COLUMN facturas.forma_pago IS 'Forma de pago SAT, por ejemplo 01 efectivo o 03 transferencia (FAC-05)';
COMMENT ON COLUMN facturas.metodo_pago IS 'Método de pago SAT: PUE o PPD (FAC-05)';
COMMENT ON COLUMN facturas.motivo_cancelacion IS 'Motivo obligatorio al cancelar una factura emitida (FAC-04)';
COMMENT ON COLUMN facturas.created_at IS 'Fecha y hora de emisión de la factura (FAC-03, SEG-06)';
COMMENT ON COLUMN facturas.updated_at IS 'Fecha y hora de la última modificación (auditoría SEG-06)';
COMMENT ON COLUMN facturas.activo IS 'Borrado lógico: TRUE vigente, FALSE eliminado; una factura no se borra (FAC-04, SEG-07)';

DROP TRIGGER IF EXISTS trg_facturas_updated_at ON facturas;
CREATE TRIGGER trg_facturas_updated_at
BEFORE UPDATE ON facturas
FOR EACH ROW EXECUTE FUNCTION fn_set_updated_at();

-- ---------------------------------------------------------------------
-- autorizaciones
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS autorizaciones (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  orden_id INTEGER NOT NULL,
  tipo tipo_autorizacion NOT NULL,
  monto_orden NUMERIC(12, 2) NOT NULL,
  aprobado BOOLEAN NOT NULL DEFAULT FALSE,
  aprobado_por VARCHAR(150) NULL,
  fecha_aprobacion TIMESTAMP NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  activo BOOLEAN NOT NULL DEFAULT TRUE,
  CONSTRAINT fk_autorizaciones_orden
    FOREIGN KEY (orden_id) REFERENCES ordenes_servicio (id)
    ON DELETE RESTRICT
    ON UPDATE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_autorizaciones_orden ON autorizaciones (orden_id);
CREATE INDEX IF NOT EXISTS idx_autorizaciones_tipo ON autorizaciones (tipo);
CREATE INDEX IF NOT EXISTS idx_autorizaciones_estado ON autorizaciones (aprobado);

COMMENT ON TABLE autorizaciones IS 'Autorizaciones del administrador por monto y por saldo pendiente (AUT-01 a AUT-08)';
COMMENT ON COLUMN autorizaciones.id IS 'Identificador interno de la autorización (AUT-05)';
COMMENT ON COLUMN autorizaciones.orden_id IS 'Orden sujeta a autorización; FK a ordenes_servicio.id (AUT-01, AUT-04)';
COMMENT ON COLUMN autorizaciones.tipo IS 'Motivo de la autorización: monto mayor a $250,000, entrega con saldo o reautorización por aumento (AUT-01, AUT-04, AUT-07)';
COMMENT ON COLUMN autorizaciones.monto_orden IS 'Total de la orden al momento de solicitar la autorización, para dejar constancia del monto (AUT-05)';
COMMENT ON COLUMN autorizaciones.aprobado IS 'Resultado: FALSE pendiente o rechazada, TRUE autorizada; solo el administrador puede autorizar (AUT-03, AUT-06)';
COMMENT ON COLUMN autorizaciones.aprobado_por IS 'Usuario administrador que resolvió la autorización (AUT-03, AUT-05)';
COMMENT ON COLUMN autorizaciones.fecha_aprobacion IS 'Fecha y hora de la resolución, con usuario y monto (AUT-05)';
COMMENT ON COLUMN autorizaciones.created_at IS 'Fecha y hora de la solicitud de autorización (AUT-05, SEG-06)';
COMMENT ON COLUMN autorizaciones.updated_at IS 'Fecha y hora de la última modificación (auditoría SEG-06)';
COMMENT ON COLUMN autorizaciones.activo IS 'Borrado lógico: TRUE vigente, FALSE eliminado; las autorizaciones no se borran (SEG-06, SEG-07)';

DROP TRIGGER IF EXISTS trg_autorizaciones_updated_at ON autorizaciones;
CREATE TRIGGER trg_autorizaciones_updated_at
BEFORE UPDATE ON autorizaciones
FOR EACH ROW EXECUTE FUNCTION fn_set_updated_at();

COMMIT;
