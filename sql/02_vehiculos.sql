BEGIN;

-- ---------------------------------------------------------------------
-- vehiculos
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS vehiculos (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cliente_id INTEGER NOT NULL,
  placas VARCHAR(20) NOT NULL,
  vin VARCHAR(50) NULL,
  marca VARCHAR(50) NOT NULL,
  modelo VARCHAR(50) NOT NULL,
  anio INTEGER NOT NULL,
  color VARCHAR(30) NULL,
  kilometraje_entrada INTEGER NULL,
  valor_aproximado NUMERIC(12, 2) NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  activo BOOLEAN NOT NULL DEFAULT TRUE,
  CONSTRAINT fk_vehiculos_cliente
    FOREIGN KEY (cliente_id) REFERENCES clientes (id)
    ON DELETE RESTRICT
    ON UPDATE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_vehiculos_cliente ON vehiculos (cliente_id);
CREATE INDEX IF NOT EXISTS idx_vehiculos_placas ON vehiculos (placas);
CREATE INDEX IF NOT EXISTS idx_vehiculos_vin ON vehiculos (vin);

COMMENT ON TABLE vehiculos IS 'Vehículos registrados de clientes (VEH-01 a VEH-08)';
COMMENT ON COLUMN vehiculos.id IS 'Identificador interno del vehículo (VEH-01)';
COMMENT ON COLUMN vehiculos.cliente_id IS 'Dueño del vehículo; FK a clientes.id (VEH-02)';
COMMENT ON COLUMN vehiculos.placas IS 'Placas del vehículo; índice para búsqueda en menos de 3 segundos (VEH-01, VEH-06)';
COMMENT ON COLUMN vehiculos.vin IS 'Número de serie / VIN del vehículo (VEH-01)';
COMMENT ON COLUMN vehiculos.marca IS 'Marca del vehículo (VEH-01)';
COMMENT ON COLUMN vehiculos.modelo IS 'Modelo del vehículo (VEH-01)';
COMMENT ON COLUMN vehiculos.anio IS 'Año modelo del vehículo (VEH-01)';
COMMENT ON COLUMN vehiculos.color IS 'Color del vehículo (VEH-01)';
COMMENT ON COLUMN vehiculos.kilometraje_entrada IS 'Kilometraje registrado al ingreso al taller (VEH-01)';
COMMENT ON COLUMN vehiculos.valor_aproximado IS 'Valor aproximado del auto para calcular el valor en custodia (VEH-07)';
COMMENT ON COLUMN vehiculos.created_at IS 'Fecha y hora de alta del registro (auditoría SEG-06)';
COMMENT ON COLUMN vehiculos.updated_at IS 'Fecha y hora de la última modificación (auditoría SEG-06)';
COMMENT ON COLUMN vehiculos.activo IS 'Borrado lógico: TRUE vigente, FALSE eliminado (SEG-07)';

DROP TRIGGER IF EXISTS trg_vehiculos_updated_at ON vehiculos;
CREATE TRIGGER trg_vehiculos_updated_at
BEFORE UPDATE ON vehiculos
FOR EACH ROW EXECUTE FUNCTION fn_set_updated_at();

-- ---------------------------------------------------------------------
-- polizas_seguro
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS polizas_seguro (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  vehiculo_id INTEGER NOT NULL,
  aseguradora VARCHAR(100) NOT NULL,
  numero_poliza VARCHAR(50) NOT NULL,
  vigencia_inicio DATE NOT NULL,
  vigencia_fin DATE NOT NULL,
  cobertura TEXT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  activo BOOLEAN NOT NULL DEFAULT TRUE,
  CONSTRAINT fk_polizas_vehiculo
    FOREIGN KEY (vehiculo_id) REFERENCES vehiculos (id)
    ON DELETE RESTRICT
    ON UPDATE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_polizas_vehiculo ON polizas_seguro (vehiculo_id);
CREATE INDEX IF NOT EXISTS idx_polizas_vigencia_fin ON polizas_seguro (vigencia_fin);

COMMENT ON TABLE polizas_seguro IS 'Pólizas de seguro de los vehículos (VEH-04, VEH-05)';
COMMENT ON COLUMN polizas_seguro.id IS 'Identificador interno de la póliza (VEH-04)';
COMMENT ON COLUMN polizas_seguro.vehiculo_id IS 'Vehículo asegurado; FK a vehiculos.id (VEH-04)';
COMMENT ON COLUMN polizas_seguro.aseguradora IS 'Nombre de la aseguradora (VEH-04)';
COMMENT ON COLUMN polizas_seguro.numero_poliza IS 'Número de póliza de seguro (VEH-04)';
COMMENT ON COLUMN polizas_seguro.vigencia_inicio IS 'Fecha de inicio de vigencia de la póliza (VEH-04)';
COMMENT ON COLUMN polizas_seguro.vigencia_fin IS 'Fecha de fin de vigencia; alerta 30 días antes (VEH-04, VEH-05)';
COMMENT ON COLUMN polizas_seguro.cobertura IS 'Detalle de la cobertura contratada (VEH-04)';
COMMENT ON COLUMN polizas_seguro.created_at IS 'Fecha y hora de alta del registro (auditoría SEG-06)';
COMMENT ON COLUMN polizas_seguro.updated_at IS 'Fecha y hora de la última modificación (auditoría SEG-06)';
COMMENT ON COLUMN polizas_seguro.activo IS 'Borrado lógico: TRUE vigente, FALSE eliminado (SEG-07)';

DROP TRIGGER IF EXISTS trg_polizas_seguro_updated_at ON polizas_seguro;
CREATE TRIGGER trg_polizas_seguro_updated_at
BEFORE UPDATE ON polizas_seguro
FOR EACH ROW EXECUTE FUNCTION fn_set_updated_at();

COMMIT;
