-- Requiere haber ejecutado 01_catalogos.sql (fn_set_updated_at y proveedores).
-- La FK compras.orden_id -> ordenes_servicio.id se agrega en el bloque 4,
-- igual que en el DDL original de MySQL, porque esa tabla aún no existe.
