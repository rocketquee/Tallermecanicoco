-- ---------------------------------------------------------------------
-- Cierra el hueco PRV-05: la compra queda ligada a la orden que la originó.
-- Se hace con DO para que el script se pueda reejecutar sin duplicar la FK.
-- ---------------------------------------------------------------------
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM pg_constraint
    WHERE conname = 'fk_compras_orden'
      AND conrelid = 'compras'::regclass
  ) THEN
    ALTER TABLE compras
      ADD CONSTRAINT fk_compras_orden
      FOREIGN KEY (orden_id) REFERENCES ordenes_servicio (id)
      ON DELETE RESTRICT
      ON UPDATE CASCADE;
  END IF;
END
$$;

