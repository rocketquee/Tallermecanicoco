-- Requisitos: VEH-01 a VEH-08
--
-- Requiere haber ejecutado 01_catalogos.sql, porque usa fn_set_updated_at()
-- y la FK hacia clientes.
-- El script es idempotente: se puede volver a ejecutar sin perder datos.
