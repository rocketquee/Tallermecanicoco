BEGIN;

-- ---------------------------------------------------------------------
-- Tipos ENUM
-- ---------------------------------------------------------------------
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM pg_type
    WHERE typname = 'estado_orden'
      AND typnamespace = 'public'::regnamespace
  ) THEN
    CREATE TYPE estado_orden AS ENUM (
      'Recibido',
      'Diagnostico',
      'Reparacion',
      'Listo',
      'Entregado',
      'Cancelado'
    );
  END IF;
END
$$;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM pg_type
    WHERE typname = 'etapa_foto'
      AND typnamespace = 'public'::regnamespace
  ) THEN
    CREATE TYPE etapa_foto AS ENUM ('Ingreso', 'Proceso', 'Entrega');
  END IF;
END
$$;

-- ---------------------------------------------------------------------
-- ordenes_servicio
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS ordenes_servicio (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cliente_id INTEGER NOT NULL,
  vehiculo_id INTEGER NOT NULL,
  mecanico_id INTEGER NULL,
  estado estado_orden NOT NULL DEFAULT 'Recibido',
  falla_reportada TEXT NULL,
  diagnostico TEXT NULL,
  total_piezas NUMERIC(12, 2) NOT NULL DEFAULT 0.00,
  total_mano_obra NUMERIC(12, 2) NOT NULL DEFAULT 0.00,
  subtotal NUMERIC(12, 2) NOT NULL DEFAULT 0.00,
  iva NUMERIC(12, 2) NOT NULL DEFAULT 0.00,
  total NUMERIC(12, 2) NOT NULL DEFAULT 0.00,
  requiere_autorizacion BOOLEAN NOT NULL DEFAULT FALSE,
  motivo_cancelacion TEXT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  activo BOOLEAN NOT NULL DEFAULT TRUE,
  CONSTRAINT fk_ordenes_cliente
    FOREIGN KEY (cliente_id) REFERENCES clientes (id)
    ON DELETE RESTRICT
    ON UPDATE CASCADE,
  CONSTRAINT fk_ordenes_vehiculo
    FOREIGN KEY (vehiculo_id) REFERENCES vehiculos (id)
    ON DELETE RESTRICT
    ON UPDATE CASCADE,
  CONSTRAINT fk_ordenes_mecanico
    FOREIGN KEY (mecanico_id) REFERENCES mecanicos (id)
    ON DELETE RESTRICT
    ON UPDATE CASCADE
);

-- Compatibilidad con instalaciones que ya tenían la tabla sin esta columna.
ALTER TABLE ordenes_servicio
  ADD COLUMN IF NOT EXISTS diagnostico TEXT NULL;

CREATE INDEX IF NOT EXISTS idx_ordenes_cliente ON ordenes_servicio (cliente_id);
CREATE INDEX IF NOT EXISTS idx_ordenes_vehiculo ON ordenes_servicio (vehiculo_id);
CREATE INDEX IF NOT EXISTS idx_ordenes_mecanico ON ordenes_servicio (mecanico_id);
CREATE INDEX IF NOT EXISTS idx_ordenes_estado ON ordenes_servicio (estado);
CREATE INDEX IF NOT EXISTS idx_ordenes_fecha ON ordenes_servicio (created_at);
CREATE INDEX IF NOT EXISTS idx_ordenes_requiere_autorizacion ON ordenes_servicio (requiere_autorizacion);

COMMENT ON TABLE ordenes_servicio IS 'Órdenes de servicio con sus cuatro etapas y totales (ORD-01 a ORD-13)';
COMMENT ON COLUMN ordenes_servicio.id IS 'Identificador interno de la orden de servicio (ORD-01)';
